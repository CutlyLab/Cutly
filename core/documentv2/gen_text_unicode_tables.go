//go:build ignore

// Command gen_text_unicode_tables freezes the exact Unicode tables used by the Text v2 document
// contract. Run it explicitly from this directory with:
//
//	go run gen_text_unicode_tables.go
//
// The command refuses any standard library Unicode version other than the one named below. The
// generated production file has no dependency on the standard library's mutable Unicode data.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"os"
	"sort"
	"unicode"
)

const frozenVersion = "17.0.0"

type frozenRange struct {
	lo     uint32
	hi     uint32
	stride uint32
}

type frozenTable struct {
	name   string
	ranges []frozenRange
}

func main() {
	if unicode.Version != frozenVersion {
		panic(fmt.Sprintf("unicode version %s does not match frozen version %s", unicode.Version, frozenVersion))
	}
	tables := []frozenTable{
		fromRangeTable("Latn", unicode.Latin),
		fromRangeTable("Hani", unicode.Han),
		fromRangeTable("Arab", unicode.Arabic),
		fromRangeTable("Common", unicode.Scripts["Common"]),
		fromRangeTable("Inherited", unicode.Scripts["Inherited"]),
		fromRangeTable("Cf", unicode.Cf),
		{name: "Cc", ranges: []frozenRange{{lo: 0, hi: 0x1f, stride: 1}, {lo: 0x7f, hi: 0x9f, stride: 1}}},
		fromRangeTable("VariationSelector", unicode.Properties["Variation_Selector"]),
		{name: "DefaultIgnorable", ranges: []frozenRange{
			{lo: 0x00ad, hi: 0x00ad, stride: 1},
			{lo: 0x034f, hi: 0x034f, stride: 1},
			{lo: 0x061c, hi: 0x061c, stride: 1},
			{lo: 0x115f, hi: 0x1160, stride: 1},
			{lo: 0x17b4, hi: 0x17b5, stride: 1},
			{lo: 0x180b, hi: 0x180f, stride: 1},
			{lo: 0x200b, hi: 0x200f, stride: 1},
			{lo: 0x202a, hi: 0x202e, stride: 1},
			{lo: 0x2060, hi: 0x206f, stride: 1},
			{lo: 0x3164, hi: 0x3164, stride: 1},
			{lo: 0xfe00, hi: 0xfe0f, stride: 1},
			{lo: 0xfeff, hi: 0xfeff, stride: 1},
			{lo: 0xffa0, hi: 0xffa0, stride: 1},
			{lo: 0xfff0, hi: 0xfff8, stride: 1},
			{lo: 0x1bca0, hi: 0x1bca3, stride: 1},
			{lo: 0x1d173, hi: 0x1d17a, stride: 1},
			{lo: 0xe0000, hi: 0xe0fff, stride: 1},
		}},
	}
	if !sameRanges(tables[6].ranges, fromRangeTable("Cc", unicode.Cc).ranges) {
		panic("explicit Cc ranges do not match Unicode 17")
	}
	if countCodePoints(tables[8].ranges) != 4174 {
		panic("explicit Default_Ignorable_Code_Point ranges do not contain the Unicode 17 total")
	}

	hash := tableHash(tables)
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by go run gen_text_unicode_tables.go; DO NOT EDIT.")
	fmt.Fprintln(&output, "//")
	fmt.Fprintln(&output, "// Source: Go unicode tables generated from Unicode 17.0.0 data.")
	fmt.Fprintln(&output, "// Default_Ignorable_Code_Point source: Unicode 17 DerivedCoreProperties.txt.")
	fmt.Fprintln(&output, "// Frozen subsets: Latn, Hani, Arab, Common, Inherited, Cf, Cc, variation selectors and Default_Ignorable_Code_Point.")
	fmt.Fprintln(&output, "package documentv2")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "const (")
	fmt.Fprintln(&output, "\tTextUnicodeValidationTableProfileV1 = \"cutly.unicode.text-validation-tables.17.0.0.v1\"")
	fmt.Fprintln(&output, "\tTextUnicodeValidationTableHashProfileV1 = \"cutly.hash.sha256.unicode-range-tables-be.v1\"")
	fmt.Fprintf(&output, "\tTextUnicodeValidationTableHashV1 = \"sha256:%x\"\n", hash)
	fmt.Fprintln(&output, ")")
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, "type frozenUnicodeRangeV1 struct { lo, hi, stride uint32 }")
	fmt.Fprintln(&output)
	for _, table := range tables {
		fmt.Fprintf(&output, "var textUnicode%sV1 = [...]frozenUnicodeRangeV1{\n", table.name)
		for _, item := range table.ranges {
			fmt.Fprintf(&output, "\t{lo: 0x%x, hi: 0x%x, stride: %d},\n", item.lo, item.hi, item.stride)
		}
		fmt.Fprintln(&output, "}")
		fmt.Fprintln(&output)
	}
	fmt.Fprintln(&output, `func textScriptSupportedV1(script string) bool {
	switch script {
	case TextScriptLatin, TextScriptHan, TextScriptArabic:
		return true
	default:
		return false
	}
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneMatchesFrozenScript(value rune, script string) bool {
	var declared []frozenUnicodeRangeV1
	switch script {
	case TextScriptLatin:
		declared = textUnicodeLatnV1[:]
	case TextScriptHan:
		declared = textUnicodeHaniV1[:]
	case TextScriptArabic:
		declared = textUnicodeArabV1[:]
	default:
		return false
	}
	return textRuneInFrozenTableV1(value, declared) ||
		textRuneInFrozenTableV1(value, textUnicodeCommonV1[:]) ||
		textRuneInFrozenTableV1(value, textUnicodeInheritedV1[:])
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneIsFrozenFormatV1(value rune) bool {
	return textRuneInFrozenTableV1(value, textUnicodeCfV1[:])
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneIsFrozenControlV1(value rune) bool {
	return textRuneInFrozenTableV1(value, textUnicodeCcV1[:])
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneIsFrozenVariationSelectorV1(value rune) bool {
	return textRuneInFrozenTableV1(value, textUnicodeVariationSelectorV1[:])
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneIsFrozenDefaultIgnorableV1(value rune) bool {
	return textRuneInFrozenTableV1(value, textUnicodeDefaultIgnorableV1[:])
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func textRuneInFrozenTableV1(value rune, table []frozenUnicodeRangeV1) bool {
	if value < 0 || value > 0x10ffff {
		return false
	}
	target := uint32(value)
	index := sortSearchFrozenUnicodeV1(table, target)
	if index == len(table) {
		return false
	}
	item := table[index]
	return target >= item.lo && target <= item.hi && (target-item.lo)%item.stride == 0
}`)
	fmt.Fprintln(&output)
	fmt.Fprintln(&output, `func sortSearchFrozenUnicodeV1(table []frozenUnicodeRangeV1, target uint32) int {
	left, right := 0, len(table)
	for left < right {
		middle := int(uint(left+right) >> 1)
		if table[middle].hi < target {
			left = middle + 1
		} else {
			right = middle
		}
	}
	return left
}`)

	if err := os.WriteFile("text_unicode_tables_v1.go", output.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

func fromRangeTable(name string, table *unicode.RangeTable) frozenTable {
	if table == nil {
		panic("missing Unicode table " + name)
	}
	result := frozenTable{name: name, ranges: make([]frozenRange, 0, len(table.R16)+len(table.R32))}
	for _, item := range table.R16 {
		result.ranges = append(result.ranges, frozenRange{lo: uint32(item.Lo), hi: uint32(item.Hi), stride: uint32(item.Stride)})
	}
	for _, item := range table.R32 {
		result.ranges = append(result.ranges, frozenRange{lo: item.Lo, hi: item.Hi, stride: item.Stride})
	}
	sort.Slice(result.ranges, func(left, right int) bool { return result.ranges[left].lo < result.ranges[right].lo })
	for index, item := range result.ranges {
		if item.lo > item.hi || item.stride == 0 || index > 0 && result.ranges[index-1].hi >= item.lo {
			panic("invalid generated Unicode ranges for " + name)
		}
	}
	return result
}

func sameRanges(left, right []frozenRange) bool {
	if len(left) != len(right) {
		return false
	}
	for index := range left {
		if left[index] != right[index] {
			return false
		}
	}
	return true
}

func countCodePoints(ranges []frozenRange) uint64 {
	var result uint64
	for _, item := range ranges {
		result += uint64(item.hi-item.lo)/uint64(item.stride) + 1
	}
	return result
}

func tableHash(tables []frozenTable) [32]byte {
	hasher := sha256.New()
	writeString(hasher, "cutly.hash.sha256.unicode-range-tables-be.v1")
	writeString(hasher, frozenVersion)
	writeUint32(hasher, uint32(len(tables)))
	for _, table := range tables {
		writeString(hasher, table.name)
		writeUint32(hasher, uint32(len(table.ranges)))
		for _, item := range table.ranges {
			writeUint32(hasher, item.lo)
			writeUint32(hasher, item.hi)
			writeUint32(hasher, item.stride)
		}
	}
	var result [32]byte
	copy(result[:], hasher.Sum(nil))
	return result
}

type byteWriter interface{ Write([]byte) (int, error) }

func writeString(writer byteWriter, value string) {
	writeUint32(writer, uint32(len(value)))
	_, _ = writer.Write([]byte(value))
}

func writeUint32(writer byteWriter, value uint32) {
	var encoded [4]byte
	binary.BigEndian.PutUint32(encoded[:], value)
	_, _ = writer.Write(encoded[:])
}
